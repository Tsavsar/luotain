// Matched loosely on purpose. Providers report brands inconsistently — "visa",
// "Visa", "VISA", "google_pay", "googlePay" — and an exact map would fall
// through to the generic plate for a card that's plainly a Visa.
export default function CardMark({ brand }) {
  const key = String(brand || '')
    .toLowerCase()
    .replace(/[\s_-]/g, '')

  if (key.includes('visa')) return <VisaMark />
  if (key.includes('mastercard') || key.includes('mc'))
    return <MastercardMark />
  if (key.includes('googlepay') || key.includes('gpay'))
    return <GooglePayMark />

  // Amex, Discover and the rest have no mark here yet, so they get a neutral
  // plate rather than the wrong logo.
  return (
    <span
      style={{
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        width: '29px',
        height: '20px',
        borderRadius: '4px',
        background: 'var(--bg-subtle)',
        color: 'var(--text-sub)',
        fontFamily: 'var(--font-sans)',
        fontSize: '8px',
        letterSpacing: '0.3px',
        textTransform: 'uppercase',
        flexShrink: 0,
      }}
    >
      {String(brand || 'Card').slice(0, 4)}
    </span>
  )
}
